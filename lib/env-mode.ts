/**
 * Два стани системи: продакшн і тест.
 *
 * У продакшні Мерчант працює: заводить угоди в Бітріксі, шле бланки в чати
 * складів, друкує ТТН, віддає замовлення на маркетплейси. У тесті він
 * робить усе те саме, окрім останнього кроку — назовні не виходить нічого.
 *
 * Чому саме так, а не «окремі ключі до тестових систем». Тестового
 * Бітрікса в нас немає, тестового MauDau й Нової Пошти теж. Якби тест
 * ходив тими самими ключами, перша ж перевірка нового коду створила б
 * справжню угоду й надіслала справжній бланк на склад — а склад пішов би
 * збирати вигадане замовлення. Гальмо стоїть у самому низу, в тих
 * функціях, якими всі ці системи викликаються: обійти його випадково,
 * написавши новий код десь нагорі, не вийде.
 *
 * Читати назовні тест може: каталог, угоди, зони. Читання нічого не
 * ламає, а без нього тестувати нема на чому.
 *
 * Вмикається однією змінною оточення. Її відсутність означає продакшн —
 * забути ввімкнути тест безпечніше, ніж забути ввімкнути продакшн.
 */

export type Mode = 'production' | 'test'

export const MODE: Mode = process.env.MERCHANT_ENV === 'test' ? 'test' : 'production'

export const isTest = MODE === 'test'
export const isProduction = MODE === 'production'

/** Як середовище зветься людською мовою — для написів в інтерфейсі */
export const MODE_LABEL = isTest ? 'ТЕСТ' : 'Продакшн'

/**
 * Що саме не поїхало назовні.
 *
 * Мовчазне гальмо гірше за відсутнє: розробник бачить, що замовлення
 * «пішло в Бітрікс», і не розуміє, чому його там немає. Тож кожен
 * затриманий виклик лишає рядок у логах виконання з назвою системи та
 * дії — звідти видно весь ланцюжок, який відпрацював би насправді.
 */
export function heldBack(system: string, action: string, details?: unknown): void {
  const what = details === undefined ? '' : ` ${JSON.stringify(details).slice(0, 300)}`
  console.info(`[ТЕСТ] не вийшло назовні → ${system}: ${action}${what}`)
}
