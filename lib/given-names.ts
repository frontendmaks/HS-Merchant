/** Апостроф пишуть трьома різними знаками  зводимо до одного */
const foldApostrophe = (s: string) => s.toLowerCase().replace(/[’'ʼ`]/g, "'")

/**
 * Як звернутись до людини.
 *
 * Коли в рядку рівно одне впізнаване ім'я  звертаємось ним. Коли жодного
 * або кілька, називаємо повністю: краще офіційно, ніж навмання.
 */
export function greetingName(full: string | null | undefined): string {
  const words = (full ?? '').trim().split(/\s+/).filter(Boolean)
  if (!words.length) return 'шановний клієнте'
  if (words.length === 1) return words[0]

  const given = words.filter(w => GIVEN_NAMES.has(foldApostrophe(w)))
  return given.length === 1 ? given[0] : words.join(' ')
}
