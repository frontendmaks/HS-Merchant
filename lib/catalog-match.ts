/**
 * Як позиція угоди впізнає свій товар у нашому каталозі.
 *
 * Тут немає ні запитів, ні мережі — самі правила. Винесено окремо саме
 * для того, щоб їх можна було перевіряти тестами: кожне з цих правил
 * уже один раз помилилось, і кожна помилка коштувала дня.
 */

/** Одиниця продажу й вага однієї штуки, як їх знає каталог. */
export interface Spec {
  unit: string
  /** Кілограмів в одній штуці; 0 — коли сайт цього не каже */
  pack: number
  productId?: string
}

/**
 * Склади, які сайт дописує до назви товару.
 *
 * Той самий товар заведено в каталозі Бітрікса окремо на кожну точку:
 * «Філе куряче - АС 2 онлайн». У нашому каталозі він один.
 */
export const WAREHOUSE_SUFFIXES = [
  'Гуртівня онлайн', 'АС 2 онлайн', 'Санта онлайн', 'М 10 онлайн',
  'МЕ ТТ Іскра', 'МЕ ЦУМ онлайн', 'МЕ Панська Гора Онлайн',
]

/** Назва без хвоста складу — те, за чим шукаємо в каталозі. */
export function bareName(title: string): string {
  const t = (title ?? '').trim()
  for (const w of WAREHOUSE_SUFFIXES) {
    const tail = ` - ${w}`
    if (t.toLowerCase().endsWith(tail.toLowerCase())) return t.slice(0, -tail.length).trim()
  }
  return t
}

/**
 * Одиниця й вага штуки з атрибутів товару.
 *
 * Вага штуки — це «Вага шт», а не «Мін». «Мін» каже, від скількох товар
 * продається: сардельки замовляються від 400 грамів, а важить одна
 * сарделька 110. Сплутавши ці два числа, Мерчант показував «1 шт = 0.4
 * кг» — учетверо більше за правду, — і оператор, набираючи «4 шт»,
 * клав у замовлення 1.6 кг замість 0.44.
 *
 * Якщо ваги штуки немає, краще не показувати перемикач узагалі:
 * вигадане число поїхало б у накладну.
 */
export function specFromAttr(attrs: Record<string, string> | null | undefined): Spec | null {
  const a = attrs?.['Одиниця']?.trim().toLowerCase()
  if (!a) return null

  const unit = a === 'кг' || a === 'л' ? 'кг' : 'шт'
  const piece = parseFloat(attrs?.['Вага шт'] ?? '')
  /* Вага штуки важить лише для вагового: у штучного «одна штука» і так
     одна штука, і перемикати там нема чого */
  return { unit, pack: unit === 'кг' && Number.isFinite(piece) && piece > 0 ? piece : 0 }
}

/**
 * Одиниця з того, що сказав Бітрікс, — коли каталог товару не знає.
 *
 * Запасний варіант, не основний: сайт ставить «шт» усьому, що заводить
 * текстом, і вагове разом з усіма.
 */
export function unitFromRow(
  measureName: string | null | undefined,
  quantity: number,
): string {
  const m = (measureName ?? '').trim().toLowerCase()
  if (m.startsWith('кг')) return 'кг'
  if (m) return 'шт'
  // Міри немає — дробова кількість сама себе видає: штуками так не беруть
  return quantity % 1 === 0 ? 'шт' : 'кг'
}

/**
 * Чи треба питати цю назву окремим запитом.
 *
 * `.in()` складає значення в один рядок через кому, і назва з комою
 * всередині в ньому розпадається — товар не знаходиться, без жодної
 * помилки. Через одну таку назву («Сир кремовий натуральний ТМ
 * "Млековіта", 125 г») ціла угода лишилась без артикулів, і 1С
 * показала комірникові порожні поля.
 */
export const needsOwnQuery = (name: string): boolean => /[,"]/.test(name)
