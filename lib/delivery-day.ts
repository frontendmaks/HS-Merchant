/**
 * День доставки — той, на який замовлення справді поїде.
 *
 * День і період обирає покупець на сайті, і Мерчант приймає їх як є.
 * Та ввечері сайт інколи лишає в замовленні сьогоднішній день —
 * замовлення №968385 оформили 19 листопада о 23:57 на «19.11, 14:00 —
 * 17:00», тобто на вікно, яке закінчилось за десять годин до того. За
 * тридцять днів таких чотири, усі між 23:41 і 23:58.
 *
 * Це не вибір клієнта: замовити доставку в минуле на сайті не можна,
 * там пропонують лише ті дні, коли ще возять. Тобто сайт віддав день,
 * якого в нього самого в переліку не було, — і виправити це означає не
 * перенести замовлення, а повернути йому день, на який його й робили.
 *
 * Лишити як є не вийде: Мерчант веде списки по днях, і замовлення з
 * учорашнім днем не видно на сьогоднішньому екрані зовсім. Воно тихо
 * лягає у вчорашній день, уже закритий, і бере номер із учорашнього
 * журналу — ящик, якого ніхто не збере.
 *
 * Правило просте й таке, як у житті: після вісімнадцятої сьогодні вже
 * не везуть, тож найближчий можливий день — наступний.
 *
 * Вісімнадцята година — не здогад: сайт і сам так робить. Зі ста
 * двадцяти п'яти вечірніх замовлень за місяць сто двадцять одне вже
 * приходить із наступним днем, і лише чотири — ті самі чотири — зі
 * сьогоднішнім.
 */

/** Після цієї години замовлення сьогодні вже не везуть */
export const EVENING_CUTOFF_HOUR = 18

export interface DeliveryDay {
  /** День, на який замовлення справді поїде */
  date: string | null
  /** Чи довелось його виправити — тоді про це треба сказати вголос */
  fixed: boolean
  /** День, який прийшов із сайту */
  from: string | null
}

/** «2026-11-19T23:57:07+02:00» → { day: '2026-11-19', hour: 23 } */
function localParts(createdAt: string): { day: string; hour: number } | null {
  const m = createdAt.match(/^(\d{4}-\d{2}-\d{2})T(\d{2}):/)
  return m ? { day: m[1], hour: Number(m[2]) } : null
}

/** Наступний календарний день. Возимо щодня, тож вихідних не пропускаємо */
function nextDay(day: string): string {
  const d = new Date(`${day}T12:00:00Z`)
  d.setUTCDate(d.getUTCDate() + 1)
  return d.toISOString().slice(0, 10)
}

/**
 * Час створення беремо з самої угоди, а не з миті огляду.
 *
 * Прохід синхронізації може дійти до замовлення за хвилину, а може за
 * годину — і тоді «зараз після вісімнадцятої» сказало б неправду про
 * замовлення, зроблене вранці.
 */
export function deliveryDayFor(
  createdAt: string | null | undefined,
  deliveryDate: string | null | undefined,
  cutoffHour: number = EVENING_CUTOFF_HOUR,
): DeliveryDay {
  const from = deliveryDate?.trim() || null
  const made = createdAt ? localParts(createdAt) : null
  if (!from || !made) return { date: from, fixed: false, from }

  // Майбутній день чіпати нема за чим: саме його покупець і обрав
  if (from > made.day) return { date: from, fixed: false, from }

  // Увечері сьогоднішній день уже не наш — найближчий можливий наступний
  if (from === made.day && made.hour >= cutoffHour) {
    return { date: nextDay(made.day), fixed: true, from }
  }

  /*
   * День у минулому не везуть узагалі.
   *
   * Такого з сайту ще не приходило, але якщо прийде, найраніше, коли
   * замовлення може поїхати, — це день, коли його зробили.
   */
  if (from < made.day) {
    return {
      date: made.hour >= cutoffHour ? nextDay(made.day) : made.day,
      fixed: true,
      from,
    }
  }

  return { date: from, fixed: false, from }
}
