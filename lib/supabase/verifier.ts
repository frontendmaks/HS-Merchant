import { createClient } from '@supabase/supabase-js'
import { timedFetch } from '@/lib/http'

/**
 * Окремий клієнт — тільки щоб перевірити підпис токена.
 *
 * Підпис перевіряється на місці, без звернення до Auth, — але щоб його
 * перевірити, потрібні відкриті ключі, і їх клієнт підтягує з Auth
 * один раз, а далі тримає при собі. «При собі» — це всередині самого
 * клієнта, тож поки клієнт будувався наново на кожен запит, ключі
 * тягнулися теж на кожен запит.
 *
 * Auth у цього проєкту має десять з'єднань із базою — так він
 * налаштований, і це видно в радниках Supabase. Кожна відкрита вкладка
 * опитує Мерчант тричі на хвилину, вкладок у зміну з десяток, і кожне
 * таке опитування просило ключі заново. Десять з'єднань на це не
 * розраховані: звернення ставали в чергу, черга доростала до
 * таймауту — і оператор бачив «Не вдалося зберегти результат».
 *
 * Тут клієнт один на весь процес. Ключі тягнуться раз і живуть, поки
 * живе екземпляр: замість тисяч звернень до Auth — одне.
 *
 * Куки йому не потрібні: токен ми дістаємо самі й передаємо явно. Саме
 * тому його й можна тримати спільним — у ньому немає нічийого сеансу,
 * а отже й немає чого переплутати між людьми.
 */
let verifier: ReturnType<typeof createClient> | undefined

export function tokenVerifier() {
  return verifier ??= createClient(
    process.env.NEXT_PUBLIC_SUPABASE_URL!,
    process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!,
    {
      auth: { persistSession: false, autoRefreshToken: false, detectSessionInUrl: false },
      global: { fetch: timedFetch(12000) },
    },
  )
}
