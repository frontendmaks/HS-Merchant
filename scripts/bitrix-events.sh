#!/bin/zsh
# Показує, що вписати у вихідний вебхук Бітрікса.
#
# Токен уже лежить у змінних Мерчанта — тут він лише показується вам, щоб
# перенести його в поле «Код застосунку». Нікуди не надсилається.
cd "$(dirname "$0")/.."

TOKEN=$(grep '^BITRIX_EVENT_TOKEN=' .env.local | head -1 | cut -d= -f2-)
if [ -z "$TOKEN" ]; then echo "✗ BITRIX_EVENT_TOKEN не знайдено в .env.local"; exit 1; fi

cat <<TXT

Передайте адміністратору порталу — Бітрікс → Розробникам → Інше →
Вихідний вебхук:

  Назва      HS Merchant — зміни угод
  Обробник   https://hs-merchant.vercel.app/api/bitrix/event?key=$TOKEN
  Події      ONCRMDEALADD, ONCRMDEALUPDATE

Ключ уже всередині посилання, тож поле «код застосунку» можна лишити
як є — Мерчант прийме і його, і ключ з адреси.

Посилання містить ключ: надсилайте його тим самим каналом, яким довіряєте
доступи, і не лишайте в спільних чатах.

Після збереження зміни в угодах приходитимуть тієї ж секунди. Розклад
лишається про запас — він догляне те, що не доставилось.

TXT
