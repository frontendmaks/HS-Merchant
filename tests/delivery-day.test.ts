import { describe, it, expect } from 'vitest'
import { deliveryDayFor } from '@/lib/delivery-day'

/*
 * Замовлення №968385: оформлене 19 листопада о 23:57 на «19.11,
 * 14:00 — 17:00». Вікно закінчилось за десять годин до того, а
 * замовлення лягло у вчорашній день, якого вже ніхто не дивиться.
 */
describe('день доставки для вечірнього замовлення', () => {
  it('після вісімнадцятої сьогоднішній день стає завтрашнім', () => {
    const day = deliveryDayFor('2026-11-19T23:57:07+02:00', '2026-11-19')
    expect(day).toEqual({ date: '2026-11-20', moved: true, from: '2026-11-19' })
  })

  it('рівно о вісімнадцятій — уже завтра', () => {
    expect(deliveryDayFor('2026-11-19T18:00:00+02:00', '2026-11-19').date).toBe('2026-11-20')
  })

  it('до вісімнадцятої сьогоднішній день лишається сьогоднішнім', () => {
    const day = deliveryDayFor('2026-11-19T17:59:59+02:00', '2026-11-19')
    expect(day).toEqual({ date: '2026-11-19', moved: false, from: '2026-11-19' })
  })

  /* Сто двадцять одне вечірнє замовлення зі ста двадцяти п'яти вже
     приходить із наступним днем — їх чіпати нема за чим */
  it('завтрашній день увечері не рухаємо', () => {
    const day = deliveryDayFor('2026-11-19T23:40:00+02:00', '2026-11-20')
    expect(day.moved).toBe(false)
    expect(day.date).toBe('2026-11-20')
  })

  it('передзамовлення на тиждень наперед лишається собою', () => {
    expect(deliveryDayFor('2026-11-19T22:10:00+02:00', '2026-11-26').date).toBe('2026-11-26')
  })

  it('кінець місяця переходить у наступний', () => {
    expect(deliveryDayFor('2026-11-30T21:00:00+02:00', '2026-11-30').date).toBe('2026-12-01')
  })

  it('кінець року теж', () => {
    expect(deliveryDayFor('2026-12-31T23:30:00+02:00', '2026-12-31').date).toBe('2027-01-01')
  })

  it('день у минулому не везуть: удень — сьогодні, ввечері — завтра', () => {
    expect(deliveryDayFor('2026-11-20T10:00:00+02:00', '2026-11-18').date).toBe('2026-11-20')
    expect(deliveryDayFor('2026-11-20T20:00:00+02:00', '2026-11-18').date).toBe('2026-11-21')
  })

  it('без дати доставки нема чого переставляти', () => {
    expect(deliveryDayFor('2026-11-19T23:57:07+02:00', null)).toEqual(
      { date: null, moved: false, from: null })
    expect(deliveryDayFor(null, '2026-11-19').date).toBe('2026-11-19')
  })

  /* Час беремо з угоди, а не з миті огляду: прохід міг дійти й за годину */
  it('година читається з самої позначки часу, а не з машини', () => {
    expect(deliveryDayFor('2026-11-19T09:00:00+02:00', '2026-11-19').moved).toBe(false)
  })
})
